"""Make enlarged far-player contact sheets from existing tracking outputs.

Uses the same rally candidates, slot colors and sequential video decoding as
make_review_sheets.py. Source frame numbers are zero-based. Feet markers are
tracking bbox bottom centers, not independently verified ground positions.
"""

import argparse
import time
from pathlib import Path

import cv2
from PIL import Image, ImageDraw, ImageFont

from make_review_sheets import (
    DEFAULT_POINTS,
    FONT,
    HERE,
    INDEX_FIELDS,
    JPEG_QUALITY,
    NAMES,
    RGB,
    TIMING_FIELDS,
    load_point,
    rally_intervals,
    update_point_csv,
    write_csv,
)


FRAME_STRIDE = 4
COLUMNS, ROWS = 2, 6
FRAMES_PER_SHEET = COLUMNS * ROWS
CROP_WIDTH, CROP_HEIGHT = 960, 300
FEET_FROM_BOTTOM = 50
SMOOTHING_ALPHA = 0.5
DEFAULT_CENTER = (960.0, 540.0)
TILE_WIDTH = 780
TILE_HEIGHT = round(CROP_HEIGHT * TILE_WIDTH / CROP_WIDTH)
FAR_SLOTS = {"far_rear", "far_front"}
BACKGROUND = (10, 18, 26)


def crop_center(people, previous):
    """Average available far feet, then smooth against the previous sample."""
    far = [person for person in people if person["slot"] in FAR_SLOTS]
    if not far:
        return previous if previous is not None else DEFAULT_CENTER
    current = (sum(person["x"] for person in far) / len(far),
               sum(person["y"] for person in far) / len(far))
    if previous is None:
        return current
    return tuple(SMOOTHING_ALPHA * value + (1 - SMOOTHING_ALPHA) * old
                 for value, old in zip(current, previous))


def crop_bounds(center, width, height):
    """Keep a fixed-size crop in bounds, with the center's feet 50px up."""
    if width < CROP_WIDTH or height < CROP_HEIGHT:
        raise ValueError(f"Source {width}x{height} is smaller than the far crop")
    left = max(0, min(round(center[0] - CROP_WIDTH / 2), width - CROP_WIDTH))
    top = max(0, min(round(center[1] - (CROP_HEIGHT - FEET_FROM_BOTTOM)),
                     height - CROP_HEIGHT))
    return left, top, left + CROP_WIDTH, top + CROP_HEIGHT


def make_tile(raw, frame, people, center, font):
    height, width = raw.shape[:2]
    left, top, right, bottom = crop_bounds(center, width, height)
    tile = Image.fromarray(cv2.cvtColor(raw[top:bottom, left:right], cv2.COLOR_BGR2RGB))
    tile = tile.resize((TILE_WIDTH, TILE_HEIGHT), Image.Resampling.LANCZOS)
    draw = ImageDraw.Draw(tile)
    visible = [person for person in people
               if left <= person["x"] < right and top <= person["y"] < bottom]
    for person in visible:
        x = (person["x"] - left) * TILE_WIDTH / CROP_WIDTH
        y = (person["y"] - top) * TILE_HEIGHT / CROP_HEIGHT
        slot = person["slot"]
        color, name = RGB[slot], NAMES[slot]
        draw.ellipse((x - 3, y - 3, x + 3, y + 3), fill=color,
                     outline="black", width=1)
        box = draw.textbbox((0, 0), name, font=font, stroke_width=1)
        label_width, label_height = box[2] - box[0], box[3] - box[1]
        label_x = max(2, min(x + 5, TILE_WIDTH - label_width - 3))
        label_y = max(26, min(y - label_height - 4, TILE_HEIGHT - label_height - 3))
        draw.text((label_x, label_y), name, font=font, fill=color,
                  stroke_width=2, stroke_fill="black")
    draw.rectangle((0, 0, TILE_WIDTH - 1, 25), fill=BACKGROUND)
    draw.text((6, 1), f"F{frame}", font=font, fill="white")
    count = f"{len(visible)}\u4eba"
    box = draw.textbbox((0, 0), count, font=font)
    draw.text((TILE_WIDTH - (box[2] - box[0]) - 6, 1), count, font=font, fill="white")
    return tile


def make_point(point, tracking_dir, output_dir, font):
    started = time.perf_counter()
    source, fps, availability, people = load_point(tracking_dir / f"point_{point:02d}", point)
    intervals = rally_intervals(availability)
    destination = output_dir / f"point_{point:02d}"
    destination.mkdir(parents=True, exist_ok=True)

    # Only outputs generated by this utility for the selected point are replaced.
    for old in destination.glob("far_F*-F*.jpg"):
        old.unlink()

    index = []
    sample_count = 0
    capture = None
    try:
        if intervals:
            capture = cv2.VideoCapture(str(source))
            assert capture.isOpened(), f"Cannot open source_video: {source}"
            assert abs(capture.get(cv2.CAP_PROP_FPS) - fps) < 0.001, "Source FPS mismatch"
            # One initial seek only; later samples and rallies advance via grab().
            first = intervals[0][0]
            assert capture.set(cv2.CAP_PROP_POS_FRAMES, first), f"Cannot seek to F{first}"
            assert round(capture.get(cv2.CAP_PROP_POS_FRAMES)) == first, "Initial seek mismatch"
            next_frame = first
            for rally, (first, last) in enumerate(intervals, start=1):
                sheet, sheet_frames = None, []
                center = None
                for frame in range(first, last + 1, FRAME_STRIDE):
                    while next_frame < frame:
                        assert capture.grab(), f"Cannot advance past F{next_frame}"
                        next_frame += 1
                        assert round(capture.get(cv2.CAP_PROP_POS_FRAMES)) == next_frame, (
                            f"Frame mismatch while advancing to F{frame}"
                        )
                    assert next_frame == frame, f"Non-monotonic target F{frame}"
                    assert capture.grab(), f"Cannot grab F{frame}"
                    assert round(capture.get(cv2.CAP_PROP_POS_FRAMES)) == frame + 1, (
                        f"Frame mismatch after grab F{frame}"
                    )
                    ok, raw = capture.retrieve()
                    assert ok and raw is not None, f"Cannot retrieve F{frame}"
                    assert round(capture.get(cv2.CAP_PROP_POS_FRAMES)) == frame + 1, (
                        f"Frame mismatch after retrieve F{frame}"
                    )
                    next_frame = frame + 1
                    assert raw.shape[:2] == (1080, 1920), (
                        f"Tracking coordinates require 1920x1080 source, got {raw.shape[:2]}"
                    )
                    frame_people = people.get(frame, [])
                    center = crop_center(frame_people, center)
                    tile = make_tile(raw, frame, frame_people, center, font)
                    if sheet is None:
                        sheet = Image.new("RGB", (TILE_WIDTH * COLUMNS, TILE_HEIGHT * ROWS),
                                          BACKGROUND)
                    cell = len(sheet_frames)
                    sheet.paste(tile, ((cell % COLUMNS) * TILE_WIDTH,
                                       (cell // COLUMNS) * TILE_HEIGHT))
                    sheet_frames.append(frame)
                    sample_count += 1
                    if len(sheet_frames) == FRAMES_PER_SHEET or frame + FRAME_STRIDE > last:
                        filename = f"far_F{sheet_frames[0]}-F{sheet_frames[-1]}.jpg"
                        sheet.save(destination / filename, format="JPEG", quality=JPEG_QUALITY)
                        index.append(dict(rally=rally, sheet=filename,
                                          first_frame=sheet_frames[0], last_frame=sheet_frames[-1],
                                          frames_in_sheet=len(sheet_frames)))
                        sheet, sheet_frames = None, []
    finally:
        if capture is not None:
            capture.release()

    write_csv(destination / "index.csv", INDEX_FIELDS, index)
    timing = dict(point=point, seconds=f"{time.perf_counter() - started:.6f}",
                  rally_intervals=len(intervals), sheets=len(index), sampled_frames=sample_count)
    update_point_csv(output_dir / "timing.csv", TIMING_FIELDS, timing)
    print(f"point {point:02d}: {len(intervals)} rally candidates, {len(index)} sheets, "
          f"{sample_count} sampled frames, {timing['seconds']} seconds", flush=True)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--points", nargs="+", type=int, default=DEFAULT_POINTS)
    parser.add_argument("--tracking-dir", type=Path, default=HERE / "tracking")
    parser.add_argument("--output-dir", type=Path, default=HERE / "review_far")
    parser.add_argument("--font", type=Path, default=FONT,
                        help="Japanese-capable font; default C:/Windows/Fonts/meiryo.ttc")
    args = parser.parse_args()
    if any(point <= 0 for point in args.points):
        parser.error("--points must contain positive point numbers")
    if not args.font.is_file():
        parser.error(f"Font missing: {args.font}; specify a Japanese font with --font")
    font = ImageFont.truetype(str(args.font), 18)
    for point in sorted(set(args.points)):
        make_point(point, args.tracking_dir.resolve(), args.output_dir.resolve(), font)


if __name__ == "__main__":
    main()
